// Keeps the README's judge-path numbers true. The data grows every cycle, so hand-written counts went stale
// (screening 11-03: "1269 vs 2433 records, 67 vs 74 tests"). This regenerates the block between the
// <!-- numbers:start --> and <!-- numbers:end --> markers from the committed data and the real command output.
//
//   node src/readme-numbers.mjs [--tests "<last line of node test/run.mjs>"]
//
// src/cycle.mjs runs it after the tests pass and commits README.md with the data.

import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { gateCoverage, readRows } from './gate.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => readFileSync(path.join(ROOT, p), 'utf8');
const arg = (k) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : null; };

export function block({ records, verifyHeads, verifyCk, tests, proof, coverage, final, gateCov = null, flows = null }) {
  const t = tests && tests.match(/(\d+) passed, (\d+) failed, (\d+) skipped/);
  const total = t ? Number(t[1]) + Number(t[2]) + Number(t[3]) : null;
  const L = [
    '<!-- numbers:start (generated by src/readme-numbers.mjs from the committed data; do not edit by hand) -->',
    `**Current numbers** (data through ${final.t}, record ${final.seq}):`,
    '',
    `- Step 1: ${total ?? '?'} tests. A judge sees \`${total ? total - 1 : '?'} passed, 0 failed, 1 skipped\`: the one SKIP is the operator check that needs the private ledger.`,
    `- Step 2: \`${verifyHeads}\` and \`${verifyCk}\`.`,
    `- Steps 6 and 8: \`chain OK up to seq ${records} of ${records}\`; the newest head in \`data/checkpoints.json\` is seq ${final.seq}, \`${final.head.slice(0, 8)}…${final.head.slice(-4)}\` (each cycle anchors it on NEAR right after the data commit; this line is read from the local file, so step 8 and step 10 are what show NEAR holds the same head).`,
    `- Step 4: \`--all\` checks ${proof.total} tx records: ${Object.entries(proof.counts).map(([k, v]) => `${k}: ${v}`).join(' · ')}.`,
    coverage ? `- Coverage (\`node src/coverage.mjs\`): the wallet had sent ${coverage.total} transactions; ${coverage.explainedTx} match a record's own tx hash, ${coverage.explainedBatch} fall inside recorded mint/crank batches, ${coverage.unexplained} are not accounted for (see Limits).` : null,
    gateCov ? `- Gate coverage (\`node src/gate.mjs coverage\`): since the gate went live (${gateCov.since}), ${gateCov.sends} gated send${gateCov.sends === 1 ? '' : 's'} in the records; ${gateCov.covered} had a \`gate_allow\` just before ${gateCov.sends === 1 ? 'it' : 'them'}, ${gateCov.bypassed} a recorded bypass, ${gateCov.missing.length} none.` : null,
    flows ? `- Where the money went (\`node src/flows.mjs\`): ${flows.sends} gated send${flows.sends === 1 ? '' : 's'}, ${flows.txs} tx${flows.txs === 1 ? '' : 's'} read on chain; ${flows.findings.length ? `${flows.findings.length} finding${flows.findings.length === 1 ? '' : 's'} (${[...new Set(flows.findings.map((f) => f.kind))].join(', ')}; seq ${[...new Set(flows.findings.map((f) => f.seq))].join(', ')})` : 'every value that left the wallet went to the agent itself, an allow-listed contract, or a 1Click deposit address whose 1Click record pays the agent, and the USDG out stayed within 2 % + 1 cent of the USD the gate was told'}.` : null,
    '<!-- numbers:end -->',
  ].filter((x) => x !== null);
  return L.join('\n');
}

function main() {
  const records = rd('data/records.jsonl').trim().split('\n').length;
  const v = spawnSync(process.execPath, ['src/chain.mjs', 'verify'], { cwd: ROOT, encoding: 'utf8' });
  const lines = (v.stdout || '').split('\n').map((l) => l.replace(/\s+/g, ' ').trim());
  const verifyHeads = lines.find((l) => l.startsWith('heads.txt:')) ?? 'heads.txt: ?';
  const verifyCk = lines.find((l) => l.startsWith('checkpoints.json:')) ?? 'checkpoints.json: ?';
  const proofJ = JSON.parse(rd('data/rh-proof.json'));
  const proof = { total: proofJ.results.length, counts: proofJ.counts };
  let coverage = null; try { coverage = JSON.parse(rd('data/coverage.json')); } catch {}
  const final = JSON.parse(rd('data/checkpoints.json')).final;
  let tests = arg('tests');
  if (!tests) { const r = spawnSync(process.execPath, ['test/run.mjs'], { cwd: ROOT, encoding: 'utf8' }); tests = (r.stdout + r.stderr).trim().split('\n').pop(); }
  const gateCov = gateCoverage(readRows(path.join(ROOT, 'data', 'records.jsonl')));
  let flows = null; try { flows = JSON.parse(rd('data/flows.json')); } catch {}
  const b = block({ records, verifyHeads, verifyCk, tests, proof, coverage, final, gateCov, flows });
  const readme = rd('README.md');
  const re = /<!-- numbers:start[\s\S]*?<!-- numbers:end -->/;
  if (!re.test(readme)) throw new Error('README.md has no <!-- numbers:start --> … <!-- numbers:end --> block');
  const next = readme.replace(re, b);
  if (next !== readme) writeFileSync(path.join(ROOT, 'README.md'), next);
  console.log(next === readme ? 'README numbers already current' : 'README numbers updated');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
